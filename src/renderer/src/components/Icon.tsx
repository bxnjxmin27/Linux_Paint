export type IconName = keyof typeof icons

export function Icon({
  name,
  size = 18,
  className,
  style
}: {
  name: IconName
  size?: number
  className?: string
  style?: CSSProperties
}): React.ReactElement {
  const C = icons[name]
  return <C className={className} style={{ fontSize: size, width: size, height: size, ...style }} />
}
